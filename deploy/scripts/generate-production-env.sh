#!/usr/bin/env sh
set -eu

APP_DIR="${APP_DIR:-$(pwd)}"
TARGET="${1:-${TARGET:-$APP_DIR/.env}}"
PUBLIC_BASE_URL="${PUBLIC_BASE_URL:-}"
ADMIN_USERNAME="${ADMIN_USERNAME:-owner}"

random_secret() {
  node -e "console.log(require('crypto').randomBytes(32).toString('base64url'))"
}

random_password() {
  node -e "console.log(require('crypto').randomBytes(24).toString('base64url'))"
}

if [ -z "$PUBLIC_BASE_URL" ]; then
  echo "PUBLIC_BASE_URL is required, example: PUBLIC_BASE_URL=https://phone.example.cn $0"
  exit 2
fi

case "$PUBLIC_BASE_URL" in
  https://*) ;;
  *)
    echo "PUBLIC_BASE_URL must start with https://"
    exit 2
    ;;
esac

if [ -f "$TARGET" ]; then
  echo "target already exists: $TARGET"
  exit 1
fi

POSTGRES_PASSWORD="$(random_password)"
ADMIN_PASSWORD="$(random_password)"
ADMIN_API_TOKEN="$(random_secret)"
WINDOWS_AGENT_TOKEN="$(random_secret)"
DEVICE_AGENT_TOKEN="$(random_secret)"
EVIDENCE_SIGNING_SECRET="$(random_secret)"

cat > "$TARGET" <<EOF
HOST=0.0.0.0
PORT=8787
NODE_ENV=production
STRICT_PRODUCTION_CONFIG=true
ALLOW_JSON_STORAGE_IN_PRODUCTION=false
STORAGE_BACKEND=postgres
DATABASE_URL=postgres://phone_cloud:$POSTGRES_PASSWORD@postgres:5432/phone_cloud
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_SSL=false
POSTGRES_STATE_KEY=default
POSTGRES_BOOTSTRAP_FROM_JSON=false
STRUCTURED_TABLE_SYNC=false
REDIS_URL=redis://redis:6379/0
REDIS_COMMAND_TIMEOUT_MS=1500
DEVICE_ONLINE_TTL_SECONDS=45
EVIDENCE_DIR=evidence
EVIDENCE_SIGNING_SECRET=$EVIDENCE_SIGNING_SECRET
EVIDENCE_URL_TTL_SECONDS=300
PUBLIC_BASE_URL=$PUBLIC_BASE_URL
TRUSTED_ORIGINS=$PUBLIC_BASE_URL
ADMIN_API_TOKEN=$ADMIN_API_TOKEN
WINDOWS_AGENT_TOKEN=$WINDOWS_AGENT_TOKEN
LEGACY_WINDOWS_AGENT_TOKEN_ENABLED=false
DEVICE_AGENT_TOKEN=$DEVICE_AGENT_TOKEN
ADMIN_USERNAME=$ADMIN_USERNAME
ADMIN_PASSWORD=$ADMIN_PASSWORD
MIN_PASSWORD_LENGTH=12
SESSION_TTL_HOURS=24
LOGIN_RATE_LIMIT_WINDOW_SECONDS=300
LOGIN_RATE_LIMIT_MAX=8
SMS_ORDER_TTL_SECONDS=300
WINDOWS_TASK_TTL_SECONDS=300
XHS_TASK_TTL_SECONDS=600
USER_MAX_WAITING_SMS=1
USER_MAX_ACTIVE_XHS_TASKS=3
DEVICE_MAX_ACTIVE_XHS_TASKS=1
MAX_QR_IMAGE_BYTES=3000000
REQUEST_TIMEOUT_SECONDS=120
KEEP_ALIVE_TIMEOUT_SECONDS=65
HEADERS_TIMEOUT_SECONDS=70
RETENTION_DAYS=30
MAX_SMS_ORDERS=5000
MAX_SMS_EVENTS=10000
MAX_SMS_MESSAGES=50000
MAX_WINDOWS_TASKS=5000
MAX_XHS_TASKS=5000
MAX_EVIDENCE_ASSETS=10000
MAX_AUDIT_EVENTS=5000
MAX_SESSIONS=5000
DATA_DIR=./data
EOF

chmod 600 "$TARGET"
echo "production env generated: $TARGET"
echo "admin username: $ADMIN_USERNAME"
echo "admin password: $ADMIN_PASSWORD"
